"""Format existing manuscript tables for the compact supplement; no data aggregation.

Run after appendix_tables and appendix_source_cells. Preserved aggregate cells for
the cost, conditional-prediction and corpus-size tables are read from
results/compact_table_cells.json; no manuscript or appendix-source archive is required.
Numeric cells are preserved without new aggregation.
"""
import argparse
import json
import re
from pathlib import Path


def tabular(text):
    return re.search(r"\\begin\{tabular\}.*?\\end\{tabular\}", text, re.S).group(0)



def format_cell(value):
    """Render a plain display value, preserving reported precision and emphasis."""
    if value is None:
        return "---"
    if value == "E. coli":
        return r"\emph{E.~coli}"
    if value == "DNABERT k=3-6, round 120":
        return r"DNABERT $k=3$--6, round 120"
    if re.fullmatch(r"\d{1,3}(,\d{3})+", value):
        return value.replace(",", "{,}")
    return value.replace("%", r"\%").replace("\u2013", "--")


def preserved_table(table, alignment):
    """Format frozen rounded measurements, not their previous manuscript source."""
    headers = table["headers"]
    assert len(headers) == len(alignment)
    lines = [r"\begin{tabular}{" + alignment + "}", r"\toprule",
             " & ".join(format_cell(x) for x in headers) + r" \\", r"\midrule"]
    for row in table["rows"]:
        assert len(row["cells"]) == len(headers)
        if row.get("rule_before"):
            lines.append(r"\midrule")
        cells = [format_cell(x) for x in row["cells"]]
        for i in row.get("emphasize", []):
            cells[i] = r"\textbf{" + cells[i] + "}"
        lines.append(" & ".join(cells) + r" \\")
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular}"])


def utility_endpoints(text):
    """Keep best/final rows; preserve model labels from omitted initial rows.

    The canonical utility table still includes the initial checkpoints. No means
    are recomputed when producing this display-only subset.
    """
    lines = []
    model = None
    omitted = 0
    for line in text.splitlines():
        if " & 0 (first) & " in line:
            assert model is None
            model = line.split(" & ", 1)[0]
            omitted += 1
            continue
        if model is not None:
            assert line.startswith(" & ") and "(best)" in line
            line = model + line
            model = None
        lines.append(line)
    assert omitted == 6 and model is None, "Unexpected utility table structure"
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="paper/tables")
    parser.add_argument("--tables", default="paper/tables", help="canonical generated tables")
    parser.add_argument("--cells", default=None, help="aggregate cells (default: results/compact_table_cells.json)")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    cells_path = Path(args.cells) if args.cells else root / "results/compact_table_cells.json"
    preserved = json.loads(cells_path.read_text(encoding="utf8"))
    assert preserved["schema_version"] == 1
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    generated = Path(args.tables)
    # Separate the replication panel so it can continue on the next page without
    # shrinking type or deleting per-seed measurements.
    sweep = tabular((generated / "a5_kcurve_perseed.tex").read_text(encoding="utf8"))
    header, body = sweep.split("\\midrule\n", 1)
    main_panel, replication = body.split("\\midrule\n", 1)
    for window, panel in [(300, main_panel + "\\bottomrule\n\\end{tabular}"),
                          (288, replication)]:
        (out / f"compact_slots_{window}.tex").write_text(
            "% Generated by pilot2.compact_appendix; numeric cells copied verbatim.\n"
            + header + "\\midrule\n" + panel + "\n", encoding="utf8")
    for name, source in [("ident", "a4_ident_perseed"), ("utility", "a6_downstream"),
                         ("hyena", "a17_hyena_epoch30"), ("overlap", "a18_overlap_prefix50")]:
        src = generated / (source + ".tex")
        if not src.exists():
            raise FileNotFoundError(
                f"Missing canonical table {src}. Run pilot2.appendix_tables and "
                "pilot2.appendix_source_cells --summary results/appendix_source_cells.json "
                f"--tables-out {generated} first.")
        text = tabular(src.read_text(encoding="utf8"))
        if name == "ident":
            text = re.sub(r"\\midrule\s*\\multicolumn\{11\}.*?(?=\\bottomrule)", "", text, flags=re.S)
            text = text.replace("checkpoint & seed", "round & seed")
        if name == "utility":
            text = text.replace("DNABERT-2 BPE", "DNABERT-2").replace("HyenaDNA medium", "HyenaDNA")
            text = text.replace(" (best held-out)", " (best)")
            text = text.replace("core prom.", "core").replace("TF binding", "TF")
            text = utility_endpoints(text)
        (out / ("compact_" + name + ".tex")).write_text(
            "% Generated by pilot2.compact_appendix; numeric cells copied verbatim.\n" + text + "\n", encoding="utf8")
    for name, alignment in [("cost", "llccc"), ("loo", "llcccc"), ("scale", "lccccc")]:
        text = preserved_table(preserved["tables"][name], alignment)
        (out / ("compact_" + name + ".tex")).write_text(
            "% Generated by pilot2.compact_appendix; numeric cells copied verbatim.\n"
            + text + "\n", encoding="utf8")


if __name__ == "__main__":
    main()
